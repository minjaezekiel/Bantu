#!/usr/bin/env python3
"""Generate pillow/ycbcr_tables.b from Pillow's own src/libImaging/ConvertYCbCr.c.

Pillow does not evaluate the JFIF matrix per pixel. It pre-multiplies each coefficient
by every possible channel value, rounds each product at 6 fractional bits, and sums the
three ROUNDED values. Because the rounding happens per channel before the sum, no single
fixed-point multiply reproduces it: fitting the combined coefficients still left +/-1
errors on 8% of pixels, and those errors are the three discarded rounding residues.

So `pillow` carries Pillow's tables. They are data, not computation, and they are
generated here rather than typed.

    tools/gen_ycbcr_tables.py                     # fetch the pinned version and emit
    tools/gen_ycbcr_tables.py --source PATH       # use a local ConvertYCbCr.c
    tools/gen_ycbcr_tables.py --check             # verify the checked-in file matches

The tables are tiny (13 x 256 INT16) and under the same PIL licence as the rest of the
quoted constants; the header of the generated file records their origin.
"""

import argparse
import os
import re
import sys
import urllib.request

PILLOW_TAG = "11.0.0"
URL = (f"https://raw.githubusercontent.com/python-pillow/Pillow/{PILLOW_TAG}"
       f"/src/libImaging/ConvertYCbCr.c")

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, os.pardir, "pillow", "ycbcr_tables.b")

ORDER = ["Y_R", "Y_G", "Y_B",
         "Cb_R", "Cb_G", "Cb_B",
         "Cr_R", "Cr_G", "Cr_B",
         "R_Cr", "G_Cb", "G_Cr", "B_Cb"]

HEADER = """// ════════════════════════════════════════════════════════════════════════
//  pillow/ycbcr_tables.b — Pillow's OWN YCbCr lookup tables.
//
//  GENERATED by tools/gen_ycbcr_tables.py from Pillow {tag}'s
//  src/libImaging/ConvertYCbCr.c. Do not edit; regenerate.
//
//  WHY TABLES AND NOT A FORMULA. Pillow does not evaluate the JFIF matrix
//  per pixel. It pre-multiplies each coefficient by every possible channel
//  value, ROUNDS each product to an integer at 6 fractional bits, and sums
//  the three rounded values:
//
//      y  =  (Y_R[r]  + Y_G[g]  + Y_B[b])  >> 6
//      cb = ((Cb_R[r] + Cb_G[g] + Cb_B[b]) >> 6) + 128
//      cr = ((Cr_R[r] + Cr_G[g] + Cr_B[b]) >> 6) + 128
//
//      r = y + ( R_Cr[cr]             >> 6)
//      g = y + ((G_Cb[cb] + G_Cr[cr]) >> 6)
//      b = y + ( B_Cb[cb]             >> 6)
//
//  Because the rounding happens PER CHANNEL, before the sum, no single
//  fixed-point multiply can reproduce it. An earlier draft of convert.b
//  fitted the combined coefficients and still differed from Pillow by +/-1
//  on 4,749 of 60,011 random pixels -- the error is the three discarded
//  rounding residues, and it cannot be fitted away. Carrying the tables is
//  the only way to be exact, and it is also FASTER here: three nd_take
//  gathers and two adds per output band, with no floating point at all.
//
//  `>> 6` on a negative value is an ARITHMETIC shift in C, i.e. floor
//  division, which is what nd_floor_divide does. Cb_R, Cb_G, Cr_G and Cr_B
//  hold negative values, so that distinction is load-bearing.
//
//  Cr_R is Cb_B: ConvertYCbCr.c defines `#define Cr_R Cb_B`, because the Cr
//  red coefficient and the Cb blue coefficient are both exactly 0.5.
// ════════════════════════════════════════════════════════════════════════

"""


def parse(src):
    tables = {}
    for m in re.finditer(r"static\s+INT16\s+(\w+)\[\]\s*=\s*\{(.*?)\};", src, re.S):
        tables[m.group(1)] = [int(v) for v in re.findall(r"-?\d+", m.group(2))]
    if "#define Cr_R Cb_B" not in src:
        sys.exit("ConvertYCbCr.c no longer aliases Cr_R to Cb_B -- check the source")
    tables["Cr_R"] = tables["Cb_B"]
    for n in ORDER:
        if n not in tables:
            sys.exit(f"table {n} not found in the source")
        if len(tables[n]) != 256:
            sys.exit(f"table {n} has {len(tables[n])} entries, expected 256")
    # The tables must be round(coeff * value * 64); spot-check two entries so a
    # silently reshaped upstream file is caught rather than embedded.
    if tables["Y_R"][1] != 19 or tables["Y_R"][4] != 77 or tables["Y_G"][1] != 38:
        sys.exit("the tables do not look like Pillow's 6-bit scaled coefficients")
    return tables


def emit(tables, tag):
    parts = [HEADER.format(tag=tag)]
    for name in ORDER:
        vals = tables[name]
        lines = [f"${name} = ["]
        for i in range(0, 256, 14):
            chunk = ", ".join(str(v) for v in vals[i:i + 14])
            lines.append("    " + chunk + ("," if i + 14 < 256 else ""))
        lines.append("];")
        parts.append("\n".join(lines))
        parts.append("")
    return "\n".join(parts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", help="a local ConvertYCbCr.c instead of fetching")
    ap.add_argument("--check", action="store_true",
                    help="compare against the checked-in file instead of writing it")
    args = ap.parse_args()

    if args.source:
        src = open(args.source, encoding="utf-8").read()
        tag = f"a local copy ({os.path.basename(args.source)})"
    else:
        print(f"fetching {URL}")
        src = urllib.request.urlopen(URL, timeout=30).read().decode("utf-8")
        tag = PILLOW_TAG

    body = emit(parse(src), tag)
    if args.check:
        if not os.path.exists(OUT):
            print("MISSING pillow/ycbcr_tables.b")
            return 1
        have = open(OUT, encoding="utf-8").read()
        strip = lambda t: "\n".join(l for l in t.splitlines() if not l.startswith("//"))
        if strip(have) != strip(body):
            print("DIFFERS pillow/ycbcr_tables.b")
            return 1
        print(f"ok  pillow/ycbcr_tables.b matches Pillow {tag}")
        return 0

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(body)
    print(f"wrote pillow/ycbcr_tables.b ({len(ORDER)} tables x 256 entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
