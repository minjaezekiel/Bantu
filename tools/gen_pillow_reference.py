        "#f00", "#0f0", "#00f", "#123", "#123456", "#12345678", "#abc",
        "#AABBCC", "#AaBbCc",
        "rgb(1,2,3)", "rgb(255,0,0)", "rgb( 10 , 20 , 30 )",
        "rgb(100%,0%,0%)", "rgb(0%,100%,50%)",
        "rgba(1,2,3,4)", "rgba(255,0,0,128)",
        "hsl(0,100%,50%)", "hsl(120,100%,50%)", "hsl(240,100%,50%)",
