#!/usr/bin/env python3
"""Generate the Pillow reference fixtures that pillow's differential tier compares against.

The point of `pillow` is that it answers what Python's Pillow answers. That claim is only
worth something if it is checked against Pillow itself, so this script runs Pillow and
writes down what it said. The output is CHECKED IN, so the test suite is reproducible on a
machine with no Python and no Pillow.

    tools/gen_pillow_reference.py            # regenerate everything
    tools/gen_pillow_reference.py --check    # verify the checked-in files still match

Fixtures land in tests/fixtures/pillow/reference/ as flat, line-oriented text, because a
Bantu test has to parse them with split() and nothing else.

Requires Pillow. Each file's header records the Pillow that produced it, and a run whose Pillow
differs from the checked-in files' REFUSES to write rather than quietly replacing one version's
answers with another's -- pass --force if that is what you mean, or --only <index> to touch just the
files this Pillow produced. The JPEG corpus (jpeg_index.txt, reference/jpeg/) was produced by
Pillow 12.3.0; everything else by 13.0.0.
"""

import argparse
import itertools
import os
import sys

try:
    import PIL
    from PIL import Image, ImageColor, ImageMode
except ImportError:
    sys.exit("this script needs Pillow: python3 -m pip install Pillow")

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, os.pardir, "tests", "fixtures", "pillow", "reference")

ALL_MODES = ["1", "L", "LA", "La", "P", "PA", "RGB", "RGBA", "RGBa", "RGBX",
             "CMYK", "YCbCr", "LAB", "HSV", "I", "I;16", "I;16L", "I;16B",
             "I;16N", "F"]


def pixels(im):
    """Every pixel, flattened, as a list. Image.getdata is deprecated in Pillow 13
    and gone in 14, and get_flattened_data does not exist before 13, so ask for
    whichever this Pillow has."""
    if hasattr(im, "get_flattened_data"):
        return list(im.get_flattened_data())
    return list(im.getdata())


def header(what):
    return [f"# {what}",
            f"# generated by tools/gen_pillow_reference.py from Pillow {PIL.__version__}",
            "# DO NOT EDIT -- regenerate instead"]


def gen_modes():
    """One line per mode: name bands basemode basetype band_names... """
    lines = header("mode table: mode bands basemode basetype bandnames")
    lines.append(f"MODES {' '.join(Image.MODES)}")
    for m in ALL_MODES:
        mi = ImageMode.getmode(m)
        im = Image.new(m, (1, 1))
        px = im.getpixel((0, 0))
        if not isinstance(px, tuple):
            px = (px,)
        lines.append(" ".join([
            m,
            str(len(mi.bands)),
            mi.basemode,
            mi.basetype,
            ",".join(mi.bands),
            ",".join(str(v) for v in px),          # Image.new's default fill
            ",".join(im.getbands()),
        ]))
    return lines


def gen_colors():
    """One line per CSS colour name: name r g b"""
    lines = header("ImageColor.colormap: name -> #rrggbb")
    for name in sorted(ImageColor.colormap):
        r, g, b = ImageColor.getrgb(name)[:3]
        lines.append(f"{name} {r} {g} {b}")
    return lines


