#!/usr/bin/env python3
"""Generate the Pillow reference fixtures that pillow's differential tier compares against.

The point of `pillow` is that it answers what Python's Pillow answers. That claim is only
worth something if it is checked against Pillow itself, so this script runs Pillow and
writes down what it said. The output is CHECKED IN, so the test suite is reproducible on a
machine with no Python and no Pillow.

    tools/gen_pillow_reference.py            # regenerate everything
    tools/gen_pillow_reference.py --check    # verify the checked-in files still match

Fixtures land in tests/fixtures/pillow/reference/ as flat, line-oriented text, because a
Bantu test has to parse them with split() and nothing else.

Requires Pillow. If the installed version differs from the one that produced the checked-in
files, the header line records both so a mismatch is explicable rather than mysterious.
"""

import argparse
import itertools
import os
import sys

try:
    import PIL
    from PIL import Image, ImageColor, ImageMode
except ImportError:
    sys.exit("this script needs Pillow: python3 -m pip install Pillow")

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, os.pardir, "tests", "fixtures", "pillow", "reference")

ALL_MODES = ["1", "L", "LA", "La", "P", "PA", "RGB", "RGBA", "RGBa", "RGBX",
             "CMYK", "YCbCr", "LAB", "HSV", "I", "I;16", "I;16L", "I;16B",
             "I;16N", "F"]


def pixels(im):
    """Every pixel, flattened, as a list. Image.getdata is deprecated in Pillow 13
    and gone in 14, and get_flattened_data does not exist before 13, so ask for
    whichever this Pillow has."""
    if hasattr(im, "get_flattened_data"):
        return list(im.get_flattened_data())
    return list(im.getdata())


def header(what):
    return [f"# {what}",
            f"# generated by tools/gen_pillow_reference.py from Pillow {PIL.__version__}",
            "# DO NOT EDIT -- regenerate instead"]


def gen_modes():
    """One line per mode: name bands basemode basetype band_names... """
    lines = header("mode table: mode bands basemode basetype bandnames")
    lines.append(f"MODES {' '.join(Image.MODES)}")
    for m in ALL_MODES:
        mi = ImageMode.getmode(m)
        im = Image.new(m, (1, 1))
        px = im.getpixel((0, 0))
        if not isinstance(px, tuple):
            px = (px,)
        lines.append(" ".join([
            m,
            str(len(mi.bands)),
            mi.basemode,
            mi.basetype,
            ",".join(mi.bands),
            ",".join(str(v) for v in px),          # Image.new's default fill
            ",".join(im.getbands()),
        ]))
    return lines


def gen_colors():
    """One line per CSS colour name: name r g b"""
    lines = header("ImageColor.colormap: name -> #rrggbb")
    for name in sorted(ImageColor.colormap):
        r, g, b = ImageColor.getrgb(name)[:3]
        lines.append(f"{name} {r} {g} {b}")
    return lines


def gen_color_specs():
    """One line per colour SPEC string: spec -> the tuple getrgb returns."""
    specs = [
        "#fff", "#ffff", "#ffffff", "#ffffffff", "#000", "#000000",
        "#f00", "#0f0", "#00f", "#123", "#123456", "#12345678", "#abc",
        "#AABBCC", "#AaBbCc",
        "rgb(1,2,3)", "rgb(255,0,0)", "rgb( 10 , 20 , 30 )",
        "rgb(100%,0%,0%)", "rgb(0%,100%,50%)",
        "rgba(1,2,3,4)", "rgba(255,0,0,128)",
        "hsl(0,100%,50%)", "hsl(120,100%,50%)", "hsl(240,100%,50%)",
        "hsl(60,100%,50%)", "hsl(0,0%,100%)", "hsl(0,0%,0%)", "hsl(180,50%,50%)",
        "hsv(0,100%,100%)", "hsv(120,100%,100%)", "hsv(240,100%,100%)",
        "hsv(60,50%,50%)", "hsb(300,100%,100%)",
        "red", "lime", "blue", "white", "black", "rebeccapurple",
        "transparent", "aliceblue", "DarkSlateGray", "  red  ",
    ]
    lines = header("ImageColor.getrgb(spec) -> tuple   (spec is tab-separated from the result)")
    for sp in specs:
        try:
            got = ImageColor.getrgb(sp)
            lines.append(f"{sp}\tOK\t{','.join(str(v) for v in got)}")
        except Exception:
            lines.append(f"{sp}\tERROR\t-")
    return lines


def gen_getcolor():
    """getcolor(spec, mode) for every mode -- the mode-aware form."""
    specs = ["red", "#336699", "white", "black", "rgba(10,20,30,40)", "lime"]
    lines = header("ImageColor.getcolor(spec, mode) -> tuple or int")
    for m in ALL_MODES:
        for sp in specs:
            try:
                got = ImageColor.getcolor(sp, m)
                if not isinstance(got, tuple):
                    got = (got,)
                lines.append(f"{m}\t{sp}\tOK\t{','.join(str(v) for v in got)}")
            except Exception:
                lines.append(f"{m}\t{sp}\tERROR\t-")
    return lines


def gen_rgb_to_l():
    """The L24 formula, spot-checked. The exhaustive check lives in the Bantu test,
    which recomputes the formula; this records Pillow's answer for a fixed sample so the
    formula itself is pinned by data and not only by code."""
    lines = header("RGB -> L   r g b -> L   (Pillow's ImagingConvert L24)")
    vals = [0, 1, 2, 3, 37, 63, 64, 127, 128, 129, 170, 200, 254, 255]
    im = Image.new("RGB", (len(vals) ** 3, 1))
    triples = list(itertools.product(vals, repeat=3))
    im.putdata(triples)
    out = pixels(im.convert("L"))
    for (r, g, b), l in zip(triples, out):
        lines.append(f"{r} {g} {b} {l}")
    return lines


def gen_convert_matrix():
    """For a fixed set of input pixels, what every mode pair converts them to.

    This is the single most valuable fixture: it pins the whole conversion matrix to
    Pillow's arithmetic, pixel by pixel, including the cases where Pillow is arguably
    wrong and `pillow` has to be wrong the same way.
    """
    probes = [(0, 0, 0), (255, 255, 255), (255, 0, 0), (0, 255, 0), (0, 0, 255),
              (1, 2, 3), (127, 128, 129), (51, 102, 153), (200, 100, 50),
              (254, 1, 128), (63, 63, 63), (170, 85, 42)]
    lines = header("convert matrix: frommode tomode inpixel -> outpixel")
    for src in ["RGB", "RGBA", "L", "LA", "1", "CMYK", "YCbCr", "HSV", "I", "F"]:
        base = Image.new("RGB", (len(probes), 1))
        base.putdata(probes)
        try:
            srcim = base.convert(src)
        except Exception:
            continue
        srcdata = pixels(srcim)
        for dst in ALL_MODES:
            try:
                dstim = srcim.convert(dst)
                dstdata = pixels(dstim)
            except Exception:
                continue
            for sp, dp in zip(srcdata, dstdata):
                if not isinstance(sp, tuple):
                    sp = (sp,)
                if not isinstance(dp, tuple):
                    dp = (dp,)
                lines.append(f"{src}\t{dst}\t{','.join(str(v) for v in sp)}"
                             f"\t{','.join(str(v) for v in dp)}")
    return lines


def gen_dither():
    """Floyd-Steinberg reference images, as raw bytes beside Pillow's answer.

    Written as binary rather than text because the point is whole images at
    several shapes: the dither's error buffer persists across rows, so a bug in
    how it is sequenced only shows up in 2-D, and a 12-pixel probe row cannot
    see it. Both an L and an RGB source for every shape, because Pillow's
    tobilevel uses the TRUNCATED (299/587/114)/1000 luminance for RGB while
    convert("L") uses the rounding L24 -- two different greys, by design.
    """
    import random
    random.seed(31337)
    out = os.path.join(OUT, "dither")
    os.makedirs(out, exist_ok=True)
    shapes = [(12, 1), (1, 12), (8, 8), (16, 9), (5, 7), (23, 3),
              (32, 32), (64, 40), (7, 13), (2, 2), (1, 1), (33, 17)]
    man = []
    for (w, h) in shapes:
        vals = [random.randrange(256) for _ in range(w * h)]
        im = Image.new("L", (w, h))
        im.putdata(vals)
        open(os.path.join(out, f"L_{w}x{h}.raw"), "wb").write(bytes(vals))
        open(os.path.join(out, f"L_{w}x{h}.bw"), "wb").write(bytes(pixels(im.convert("1"))))

        rvals = [(random.randrange(256), random.randrange(256), random.randrange(256))
                 for _ in range(w * h)]
        rim = Image.new("RGB", (w, h))
        rim.putdata(rvals)
        open(os.path.join(out, f"RGB_{w}x{h}.raw"), "wb").write(
            bytes(b for p in rvals for b in p))
        open(os.path.join(out, f"RGB_{w}x{h}.bw"), "wb").write(bytes(pixels(rim.convert("1"))))
        man.append(f"{w} {h}")
    open(os.path.join(out, "MANIFEST"), "w").write("\n".join(man) + "\n")
    return header("dither corpus index (the images themselves are in reference/dither/)") + \
           [f"{w} {h}" for (w, h) in shapes]


def gen_colorspace():
    """A dense probe through RGB -> YCbCr and RGB -> HSV and back.

    These two were the last conversions to be matched, and they were matched by
    reading Pillow's C rather than by fitting: YCbCr sums three PRE-ROUNDED
    table lookups (so no combined multiplier reproduces it) and HSV computes in
    32-bit float with a `fmod(h/6 + 1, 1)` fold. A dense sample is kept so a
    regression in either is caught by value, not by eye.
    """
    import random
    random.seed(4242)
    pts = [(0, 0, 0), (255, 255, 255), (255, 0, 0), (0, 255, 0), (0, 0, 255),
           (1, 2, 3), (127, 128, 129), (128, 128, 128), (254, 255, 1), (63, 63, 63),
           (88, 72, 242), (127, 217, 199), (121, 72, 36), (136, 187, 154)]
    pts += [(random.randrange(256), random.randrange(256), random.randrange(256))
            for _ in range(3000)]
    src = Image.new("RGB", (len(pts), 1))
    src.putdata(pts)
    ycc = pixels(src.convert("YCbCr"))
    hsv = pixels(src.convert("HSV"))
    lines = header("RGB -> YCbCr and HSV:  r g b  ycbcr  hsv")
    for p, y, v in zip(pts, ycc, hsv):
        lines.append(f"{p[0]} {p[1]} {p[2]} "
                     f"{y[0]},{y[1]},{y[2]} {v[0]},{v[1]},{v[2]}")
    # and the inverse, from YCbCr and HSV back to RGB
    yim = Image.new("YCbCr", (len(pts), 1))
    yim.putdata(ycc)
    yback = pixels(yim.convert("RGB"))
    him = Image.new("HSV", (len(pts), 1))
    him.putdata(hsv)
    hback = pixels(him.convert("RGB"))
    lines.append("# --- inverse:  ycbcr -> rgb   hsv -> rgb ---")
    for y, v, yr, hr in zip(ycc, hsv, yback, hback):
        lines.append(f"INV {y[0]},{y[1]},{y[2]} {yr[0]},{yr[1]},{yr[2]} "
                     f"{v[0]},{v[1]},{v[2]} {hr[0]},{hr[1]},{hr[2]}")
    return lines


def gen_palette():
    """RGB -> P reference images, dithered and not, as raw bytes.

    Two purposes. The undithered ones pin the web cube's nearest-entry rule
    (4-step quantisation, lowest-index ties). The dithered 2-D ones pin the
    three-channel error accumulator -- and locate the one place pillow
    deliberately differs from Pillow: Convert.c ends each row by writing
    blue's accumulators into all three channel slots, discarding red's and
    green's, so Pillow's own last column is corrupted from row two onward.
    pillow writes each channel's own carry, so the difference is confined to
    the last column, which the test asserts.
    """
    import random
    random.seed(90210)
    out = os.path.join(OUT, "palette")
    os.makedirs(out, exist_ok=True)
    shapes = [(12, 1), (8, 6), (16, 9), (5, 7), (24, 24)]
    man = []
    for (w, h) in shapes:
        vals = [(random.randrange(256), random.randrange(256), random.randrange(256))
                for _ in range(w * h)]
        im = Image.new("RGB", (w, h))
        im.putdata(vals)
        open(os.path.join(out, f"RGB_{w}x{h}.raw"), "wb").write(
            bytes(b for p in vals for b in p))
        nod = im.convert("P", dither=Image.Dither.NONE)
        open(os.path.join(out, f"RGB_{w}x{h}.none"), "wb").write(bytes(pixels(nod)))
        dit = im.convert("P")
        open(os.path.join(out, f"RGB_{w}x{h}.fs"), "wb").write(bytes(pixels(dit)))
        man.append(f"{w} {h}")
    open(os.path.join(out, "MANIFEST"), "w").write("\n".join(man) + "\n")
    return header("palette corpus index (images in reference/palette/)") + \
           [f"{w} {h}" for (w, h) in shapes]


def gen_resample():
    """resize() reference images: every filter, several modes, up and down.

    Written as raw bytes beside Pillow's answer, because resampling is a
    whole-image property: the coefficient bounds differ per output column, so
    a probe pixel proves nothing about the ones beside it.

    Covers the behaviours that are easy to miss and that Pillow's Python layer
    adds on top of the C:
      * modes "1" and "P" force NEAREST whatever filter is asked for
      * "LA" and "RGBA" are premultiplied (converted to La/RGBa) before any
        non-NEAREST resize and converted back after, so transparent pixels do
        not bleed colour into their neighbours
    """
    import random
    random.seed(1848)
    out = os.path.join(OUT, "resample")
    os.makedirs(out, exist_ok=True)

    filters = {"NEAREST": Image.Resampling.NEAREST,
               "LANCZOS": Image.Resampling.LANCZOS,
               "BILINEAR": Image.Resampling.BILINEAR,
               "BICUBIC": Image.Resampling.BICUBIC,
               "BOX": Image.Resampling.BOX,
               "HAMMING": Image.Resampling.HAMMING}
    # source shapes paired with target shapes: downscale, upscale, identity,
    # non-square, and the degenerate 1-pixel cases.
    jobs = [(16, 12, 8, 6), (16, 12, 32, 24), (16, 12, 16, 12),
            (16, 12, 5, 11), (16, 12, 1, 1), (7, 5, 13, 3), (9, 9, 2, 7)]
    modes = ["L", "RGB", "RGBA", "LA", "CMYK", "I", "F", "1", "P"]

    man = []
    for mi, m in enumerate(modes):
        for (sw, sh, dw, dh) in jobs:
            base = Image.new("RGB", (sw, sh))
            base.putdata([(random.randrange(256), random.randrange(256),
                           random.randrange(256)) for _ in range(sw * sh)])
            try:
                src = base.convert(m)
            except Exception:
                continue
            elem = {"I": "<i4", "F": "<f4"}.get(m)
            tag = f"{m.replace(';','_')}_{sw}x{sh}_{dw}x{dh}"
            open(os.path.join(out, tag + ".src"), "wb").write(src.tobytes())
            for fname, f in filters.items():
                try:
                    got = src.resize((dw, dh), f)
                except Exception as e:
                    man.append(f"{m} {sw} {sh} {dw} {dh} {fname} ERROR")
                    continue
                open(os.path.join(out, f"{tag}_{fname}.dst"), "wb").write(got.tobytes())
                man.append(f"{m} {sw} {sh} {dw} {dh} {fname} OK")
    open(os.path.join(out, "MANIFEST"), "w").write("\n".join(man) + "\n")
    return header("resample corpus index (images in reference/resample/)") + man


GENERATORS = {
    "resample_index.txt": gen_resample,
    "palette_index.txt": gen_palette,
    "dither_index.txt": gen_dither,
    "colorspace.txt": gen_colorspace,
    "modes.txt": gen_modes,
    "colors.txt": gen_colors,
    "color_specs.txt": gen_color_specs,
    "getcolor.txt": gen_getcolor,
    "rgb_to_l.txt": gen_rgb_to_l,
    "convert_matrix.txt": gen_convert_matrix,
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="compare against the checked-in files instead of writing them")
    args = ap.parse_args()

    os.makedirs(OUT, exist_ok=True)
    rc = 0
    for name, fn in sorted(GENERATORS.items()):
        body = "\n".join(fn()) + "\n"
        path = os.path.join(OUT, name)
        if args.check:
            if not os.path.exists(path):
                print(f"  MISSING  {name}")
                rc = 1
                continue
            have = open(path, encoding="utf-8").read()
            # the generator line carries the Pillow version, so compare the data only
            strip = lambda t: "\n".join(l for l in t.splitlines() if not l.startswith("#"))
            if strip(have) != strip(body):
                print(f"  DIFFERS  {name}")
                rc = 1
            else:
                print(f"  ok       {name}  ({len(strip(body).splitlines())} rows)")
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(body)
            print(f"  wrote    {name}  ({len(body.splitlines())} lines)")
    return rc


if __name__ == "__main__":
    sys.exit(main())
