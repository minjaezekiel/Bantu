#!/usr/bin/env python3
"""Generate pillow/exif_tags.b from Pillow's own ExifTags dictionaries.

Every name in EXIF is defined by the EXIF specification and recorded in
Pillow's PIL/ExifTags.py. Retyping 274 tag names by hand is a guarantee of a
typo in one of them, so they are generated instead and the generator is
checked in beside the output.

    tools/gen_exif_tags.py            # write pillow/exif_tags.b
    tools/gen_exif_tags.py --check    # verify the checked-in file matches
"""

import argparse
import os
import sys

try:
    import PIL
    from PIL import ExifTags
except ImportError:
    sys.exit("this script needs Pillow: python3 -m pip install Pillow")

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, os.pardir, "pillow", "exif_tags.b")


def dict_lines(name, mapping, comment):
    lines = [f"// {comment}", f"${name} = {{"]
    for k in sorted(mapping):
        v = str(mapping[k]).replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    "{k}": "{v}",')
    if len(lines) > 2:
        lines[-1] = lines[-1][:-1]
    lines.append("};")
    lines.append("")
    return lines


def name_lines(name, enum, comment):
    """name -> number, for the Base/GPS/Interop enums Pillow exposes."""
    lines = [f"// {comment}", f"${name} = {{"]
    for m in enum:
        lines.append(f'    "{m.name}": {m.value},')
    if len(lines) > 2:
        lines[-1] = lines[-1][:-1]
    lines.append("};")
    lines.append("")
    return lines


def body():
    out = [
        "// ======================================================================",
        "//  pillow/exif_tags.b -- GENERATED by tools/gen_exif_tags.py from",
        f"//  Pillow {PIL.__version__}'s PIL/ExifTags.py. DO NOT EDIT; regenerate.",
        "//",
        "//  Pillow's ExifTags module, name for name: TAGS, GPSTAGS, IFD, Base,",
        "//  GPS and Interop. Keys are STRINGS because a Bantu dict is keyed by",
        "//  string; exif.b's tag_name() takes a number and does the str().",
        "// ======================================================================",
        "",
    ]
    out += dict_lines("TAGS", ExifTags.TAGS, "ExifTags.TAGS: tag number -> name (TIFF and EXIF)")
    out += dict_lines("GPSTAGS", ExifTags.GPSTAGS, "ExifTags.GPSTAGS: tag number -> name, inside the GPS IFD")
    out += name_lines("IFD", ExifTags.IFD, "ExifTags.IFD: the sub-IFD pointers, by name")
    out += name_lines("BASE", ExifTags.Base, "ExifTags.Base: every base tag, by name")
    out += name_lines("GPS", ExifTags.GPS, "ExifTags.GPS: every GPS tag, by name")
    out += name_lines("INTEROP", ExifTags.Interop, "ExifTags.Interop: every interoperability tag, by name")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = body()
    if args.check:
        if not os.path.exists(OUT):
            print("MISSING pillow/exif_tags.b")
            return 1
        have = open(OUT, encoding="utf-8").read()
        strip = lambda t: "\n".join(l for l in t.splitlines() if not l.startswith("//  Pillow "))
        if strip(have) != strip(text):
            print("DIFFERS pillow/exif_tags.b")
            return 1
        print("ok      pillow/exif_tags.b")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote   pillow/exif_tags.b ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
